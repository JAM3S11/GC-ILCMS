// Synthetic chromatogram generation
export const CHROMATOGRAM_DATA: Array<{ time: number; intensity: number }> = [];
for (let t = 2.0; t <= 15.0; t += 0.05) {
  const roundT = Math.round(t * 100) / 100;
  let baseNoise = 120 + Math.sin(t * 8) * 15 + Math.random() * 20;

  // Peak 1: Phenacetin @ 6.18 min
  const peak1 = 3800 * Math.exp(-Math.pow(roundT - 6.18, 2) / (2 * 0.03 * 0.03));
  // Peak 2: Lidocaine @ 7.05 min
  const peak2 = 1450 * Math.exp(-Math.pow(roundT - 7.05, 2) / (2 * 0.04 * 0.04));
  // Peak 3: Cocaine @ 8.42 min (major peak)
  const peak3 = 9800 * Math.exp(-Math.pow(roundT - 8.42, 2) / (2 * 0.05 * 0.05));

  CHROMATOGRAM_DATA.push({
    time: roundT,
    intensity: Math.round(baseNoise + peak1 + peak2 + peak3),
  });
}

// Synthetic UV-Vis Spectrum (200 - 350 nm)
export const UV_SPECTRUM_DATA: Array<{ wavelength: number; absorbance: number }> = [];
